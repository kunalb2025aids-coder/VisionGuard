"""Telemetry API - sensor simulation endpoints."""
import logging
from typing import List, Optional
from fastapi import APIRouter, Depends, HTTPException, Query
from sqlalchemy.orm import Session

from backend.app.models.database import get_db
from backend.app.models.entities import Asset, AnomalyPrediction
from backend.app.services.telemetry_service import TelemetryService, SCENARIOS
from backend.app.services.prediction_service import PredictionService
from backend.app.services.event_bus import manager

router = APIRouter(prefix="/api/telemetry", tags=["Telemetry"])
logger = logging.getLogger("visionguard.telemetry_router")


def _get_asset_or_404(db: Session, asset_code: str) -> Asset:
    asset = db.query(Asset).filter(Asset.asset_id == asset_code).first()
    if not asset:
        raise HTTPException(status_code=404, detail=f"Asset '{asset_code}' not found. Seed assets first via GET /api/assets.")
    return asset


@router.get("/scenarios")
def list_scenarios():
    """List available simulation scenarios."""
    return {
        "scenarios": SCENARIOS,
        "note": "All telemetry is software simulation. source=simulation is always set."
    }


@router.get("/channels")
def list_channels():
    """List sensor channels and their thresholds."""
    from backend.app.services.telemetry_service import SENSOR_CHANNELS
    return {"channels": SENSOR_CHANNELS}


@router.get("/latest")
def get_latest_readings(
    asset_code: str = Query("CONV-01"),
    db: Session = Depends(get_db),
):
    """Return latest reading per channel for the given asset."""
    _get_asset_or_404(db, asset_code)
    readings = TelemetryService.get_latest_readings(db, asset_code)
    return {
        "asset_code": asset_code,
        "readings": readings,
        "simulation_badge": "SIMULATION",
        "note": "Values are generated by software simulation. source=simulation for all records.",
    }


@router.get("/history")
def get_telemetry_history(
    asset_code: str = Query("CONV-01"),
    channel: Optional[str] = Query(None),
    limit: int = Query(100, ge=1, le=500),
    db: Session = Depends(get_db),
):
    """Return time-series telemetry history."""
    _get_asset_or_404(db, asset_code)
    history = TelemetryService.get_history(db, asset_code, channel, limit)
    return {
        "asset_code": asset_code,
        "channel": channel,
        "count": len(history),
        "readings": history,
        "simulation_badge": "SIMULATION",
    }


@router.post("/simulate")
async def run_simulation_step(
    asset_code: str = Query("CONV-01"),
    scenario: str = Query("normal"),
    step: int = Query(0, ge=0),
    seed: Optional[int] = Query(None),
    persist: bool = Query(True),
    db: Session = Depends(get_db),
):
    """
    Generate one telemetry snapshot and optionally persist it.
    Broadcasts telemetry.updated event to WebSocket clients.
    """
    if scenario not in SCENARIOS:
        raise HTTPException(status_code=400, detail=f"Unknown scenario '{scenario}'. Available: {list(SCENARIOS)}")
    asset = _get_asset_or_404(db, asset_code)

    readings = TelemetryService.generate_snapshot(asset_code, scenario, step, seed)

    if persist:
        TelemetryService.persist_snapshot(db, asset.id, asset_code, scenario, step, seed)

    # Threshold analysis
    anomalies = PredictionService.analyze_readings(readings)

    # Persist anomaly indicators
    for anom in anomalies:
        pred = AnomalyPrediction(
            asset_id=asset.id,
            asset_code=asset_code,
            prediction_type=anom["prediction_type"],
            sensor_channel=anom.get("sensor_channel"),
            anomaly_score=anom.get("anomaly_score"),
            threshold_value=anom.get("threshold_value"),
            actual_value=anom.get("actual_value"),
            evidence=anom.get("evidence"),
            severity=anom["severity"],
            model_version=anom.get("model_version"),
            source="simulation",
        )
        db.add(pred)
    if anomalies:
        db.commit()

    # Broadcast to WebSocket clients
    import asyncio
    import asyncio
    try:
        await manager.broadcast("telemetry.updated", {
            "asset_code": asset_code,
            "scenario": scenario,
            "step": step,
            "readings": readings,
            "anomalies_count": len(anomalies),
            "simulation_badge": "SIMULATION",
        })
    except Exception:
        pass  # Non-critical

    return {
        "asset_code": asset_code,
        "scenario": scenario,
        "step": step,
        "readings": readings,
        "anomaly_indicators": anomalies,
        "persisted": persist,
        "simulation_badge": "SIMULATION",
        "disclaimer": "All values are software-simulated. Not real sensor hardware data.",
    }


@router.post("/demo/scenarios/{scenario_name}")
async def run_demo_scenario(
    scenario_name: str,
    asset_code: str = Query("CONV-01"),
    steps: int = Query(10, ge=1, le=50),
    seed: int = Query(42),
    db: Session = Depends(get_db),
):
    """
    Run a complete demo scenario with multiple steps (seeded/deterministic).
    Useful for populating history charts.
    """
    if scenario_name not in SCENARIOS:
        raise HTTPException(status_code=400, detail=f"Unknown scenario '{scenario_name}'.")
    asset = _get_asset_or_404(db, asset_code)

    all_readings = []
    all_anomalies = []
    for step in range(steps):
        readings = TelemetryService.generate_snapshot(asset_code, scenario_name, step, seed + step)
        TelemetryService.persist_snapshot(db, asset.id, asset_code, scenario_name, step, seed + step)
        anomalies = PredictionService.analyze_readings(readings)
        all_readings.extend(readings)
        all_anomalies.extend(anomalies)
        for anom in anomalies:
            pred = AnomalyPrediction(
                asset_id=asset.id,
                asset_code=asset_code,
                prediction_type=anom["prediction_type"],
                sensor_channel=anom.get("sensor_channel"),
                actual_value=anom.get("actual_value"),
                evidence=anom.get("evidence"),
                severity=anom["severity"],
                model_version=anom.get("model_version"),
                source="simulation",
            )
            db.add(pred)
    db.commit()

    return {
        "scenario": scenario_name,
        "asset_code": asset_code,
        "steps_generated": steps,
        "total_readings": len(all_readings),
        "total_anomaly_indicators": len(all_anomalies),
        "simulation_badge": "SIMULATION",
        "seed": seed,
        "disclaimer": "Demo scenario values are deterministic software simulations. Not real sensor data.",
    }
